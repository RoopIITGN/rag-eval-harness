"""
Run every retrieval configuration over the verified eval set, then write
reports/ablation.md.

Retrieval happens ONCE per (query, config, mode) and the ranked list is saved
to reports/runs.jsonl. Every number in the report is computed from that file:
recall@5 and recall@20 are the same retrieval at two cutoffs, never a second
query against the index.

The saved lists drop chunk text and keep only what the metrics need -- document,
character offsets, token count, scores. That keeps the file small enough to
commit, which means anyone can recompute the numbers, or argue with them,
without Azure credentials.

Usage
  PYTHONPATH=src python src/run_ablation.py            # retrieve, then report
  PYTHONPATH=src python src/run_ablation.py --report   # reuse runs.jsonl
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import metrics
import retrieve

ROOT = Path(__file__).resolve().parents[1]
GOLD = ROOT / "data/goldset.jsonl"
RUNS = ROOT / "reports/runs.jsonl"
REPORT = ROOT / "reports/ablation.md"

CONFIGS = ["256-fixed", "512-fixed", "512-recursive"]
MODES = ["bm25", "dense", "hybrid", "hybrid+rerank"]
K_MAIN, K_CEIL = 5, 20
BUDGETS = [1280, 2560]          # tokens: top-5 of 256 and of 512
HEADLINE = "512-recursive"      # config used for the per-mode breakdowns

KEEP = ("rank", "id", "doc_id", "char_start", "char_end", "token_count",
        "search_score", "rerank_score")


def do_retrieval(gold: dict) -> None:
    RUNS.parent.mkdir(parents=True, exist_ok=True)
    total = len(gold) * len(CONFIGS) * len(MODES)
    done, t0 = 0, time.time()
    with RUNS.open("w", encoding="utf-8") as f:
        for config in CONFIGS:
            for mode in MODES:
                for qid, g in gold.items():
                    results = retrieve.retrieve(g["query"], config, mode, top=K_CEIL)
                    f.write(json.dumps({
                        "config": config, "mode": mode, "query_id": qid,
                        "results": [{k: r[k] for k in KEEP if k in r} for r in results],
                    }) + "\n")
                    done += 1
                    if done % 50 == 0:
                        rate = done / (time.time() - t0)
                        print(f"  {done}/{total}  {rate:.1f}/s  "
                              f"eta {(total - done) / rate / 60:.1f}m", end="\r")
                print(f"  {config:16s} {mode:14s} done" + " " * 20)
    print(f"\nretrieval written -> {RUNS}")


def pct(hits: int, n: int) -> str:
    return f"{100 * hits / n:.1f}%" if n else "-"


def build_report(runs, gold) -> str:
    n = len(gold)
    out: list[str] = []
    w = out.append

    w("# Ablation\n")
    w(f"Generated by `src/run_ablation.py` over {n} verified queries. "
      f"Retrieval pool is {K_CEIL}; every metric is computed from "
      f"`reports/runs.jsonl`.\n")

    # ---- headline: every config x every mode -----------------------------
    w("## recall@5 and recall@20\n")
    w("| Configuration | Mode | recall@5 | 95% CI | recall@20 |")
    w("|---|---|---|---|---|")
    for config in CONFIGS:
        for mode in MODES:
            h5, n5 = metrics.recall_at_k(runs, gold, config, mode, K_MAIN)
            h20, _ = metrics.recall_at_k(runs, gold, config, mode, K_CEIL)
            lo, hi = metrics.bootstrap_ci(runs, gold, config, mode, K_MAIN)
            w(f"| {config} | {mode} | {pct(h5, n5)} | "
              f"{100*lo:.1f}–{100*hi:.1f}% | {pct(h20, n5)} |")
    w("")
    w("The gap between @5 and @20 is the headroom available to reranking: it "
      "separates *the retriever never found it* from *the retriever found it "
      "and ranked it badly*.\n")

    # ---- subgroup --------------------------------------------------------
    w(f"## recall@{K_MAIN} by query type — {HEADLINE}\n")
    types = sorted({g["query_type"] for g in gold.values()})
    w("| Mode | " + " | ".join(types) + " |")
    w("|---" * (len(types) + 1) + "|")
    for mode in MODES:
        sub = metrics.recall_by_subgroup(runs, gold, HEADLINE, mode, K_MAIN)
        cells = [pct(*sub.get(t, (0, 0))) for t in types]
        w(f"| {mode} | " + " | ".join(cells) + " |")
    w("")
    counts = {t: sum(1 for g in gold.values() if g["query_type"] == t) for t in types}
    w("Query counts: " + ", ".join(f"{t} {counts[t]}" for t in types) + ".\n")
    w("Blended recall averages this away. `exact_id` is where BM25 earns its "
      "place and dense retrieval fails; `supersession` and `multi_hop` are the "
      "designed slices, and are the hardest by construction.\n")

    # ---- equal token budget ---------------------------------------------
    w("## Recall at a fixed token budget — hybrid + rerank\n")
    w("| Configuration | " + " | ".join(f"{b} tokens" for b in BUDGETS) + " |")
    w("|---" * (len(BUDGETS) + 1) + "|")
    for config in CONFIGS:
        cells = [pct(*metrics.recall_at_budget(runs, gold, config, "hybrid+rerank", b))
                 for b in BUDGETS]
        w(f"| {config} | " + " | ".join(cells) + " |")
    w("")
    w("Fixed-k quietly favours larger chunks, because top-5 of 512-token chunks "
      "is twice the context of top-5 of 256-token chunks. This table gives each "
      "configuration the same number of tokens.\n")

    # ---- paired tests ----------------------------------------------------
    w("## Paired comparisons (McNemar)\n")
    w("Only queries where two runs disagree carry information. `a_only` is how "
      "many queries the first run answered and the second missed.\n")
    w("| Comparison | a_only | b_only | discordant | p |")
    w("|---|---|---|---|---|")

    pairs = [((HEADLINE, "bm25"), (HEADLINE, "hybrid")),
             ((HEADLINE, "dense"), (HEADLINE, "hybrid")),
             ((HEADLINE, "hybrid"), (HEADLINE, "hybrid+rerank"))]
    pairs += [((a, "hybrid+rerank"), (b, "hybrid+rerank"))
              for a, b in [("256-fixed", "512-fixed"), ("512-fixed", "512-recursive")]]
    for ka, kb in pairs:
        m = metrics.mcnemar_runs(runs, gold, ka, kb, K_MAIN)
        label = (f"{ka[1]} vs {kb[1]} ({HEADLINE})" if ka[0] == kb[0]
                 else f"{ka[0]} vs {kb[0]} (hybrid+rerank)")
        w(f"| {label} | {m['a_only']} | {m['b_only']} | "
          f"{m['discordant']} | {m['p_value']:.3f} |")
    w("")

    # ---- what nothing retrieves -----------------------------------------
    missed = []
    for qid, g in gold.items():
        if all(metrics.satisfied_at_rank(runs[(c, m)][qid], g["gold_spans"],
                                         g.get("require", "all")) is None
               for c in CONFIGS for m in MODES if qid in runs[(c, m)]):
            missed.append((qid, g))
    w(f"## Retrieved by no configuration — {len(missed)} of {n}\n")
    if missed:
        w("| Query | Type | Documents |")
        w("|---|---|---|")
        for qid, g in sorted(missed)[:25]:
            docs = ", ".join(sorted({s["doc_id"] for s in g["gold_spans"]}))
            w(f"| {qid}. {g['query'][:70]} | {g['query_type']} | {docs} |")
        w("")
        w("These are the honest failures: no chunking configuration and no "
          "retrieval mode surfaces enough of the gold span. Multi-span queries "
          "appear here when one span is found and another is not.\n")
    else:
        w("Every verified query is answerable by at least one configuration.\n")

    return "\n".join(out) + "\n"


def main() -> None:
    gold = metrics.load_gold(str(GOLD))
    if not gold:
        sys.exit("no verified queries in goldset.jsonl")
    print(f"{len(gold)} verified queries")

    if "--report" not in sys.argv:
        print(f"retrieving {len(gold) * len(CONFIGS) * len(MODES)} ranked lists")
        do_retrieval(gold)
    elif not RUNS.exists():
        sys.exit(f"{RUNS} not found -- run without --report first")

    runs = metrics.load_runs(str(RUNS))
    REPORT.write_text(build_report(runs, gold), encoding="utf-8")
    print(f"report written -> {REPORT}")


if __name__ == "__main__":
    main()
